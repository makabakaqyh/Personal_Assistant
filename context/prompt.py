# 会话摘要提示词 ==========================================================================================================
summary_system_prompt = SystemMessagePromptTemplate.from_template(
    """
<角色定义>
你是一个会话状态摘要器。
你的任务是将“本轮新增对话”合并到“旧摘要”中，生成一个准确、简洁、可供后续 Agent 使用的新摘要。
</角色定义>

<规则>
- 只记录对后续对话有帮助的信息。
- 保留用户当前目标、已经完成的工作、未完成事项、关键决策、约束和必要背景。
- 不要记录寒暄、重复内容和无关细节。
- 只能使用输入中明确出现的信息，不要猜测或补充事实。
- 如果新对话纠正了旧摘要，以新对话为准。
- 摘要不要超过 500 字。
- 如果摘要字数过多，优先删除背景、重复描述和次要细节，保留当前目标、未完成事项、关键决策和约束。
- 如果旧摘要为空，只根据本轮新增对话生成摘要。
- 输出内容应让另一个 Agent 能够直接继续处理会话。
- 只输出 JSON，不要输出 Markdown、解释或额外文字。
</规则>
"""
)

summary_human_prompt = HumanMessagePromptTemplate.from_template(
    """
<旧摘要>
{old_summary}
</旧摘要>

<本轮新增消息>
{new_message}
</本轮新增消息>

请将本轮新增对话合并到旧摘要中，并输出新的摘要。

<输出格式>
{{
  "summary": "新的会话摘要",
}}
</输出格式>
"""
)

summary_prompt = ChatPromptTemplate.from_messages([summary_system_prompt, summary_human_prompt])
